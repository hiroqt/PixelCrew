/**
 * PIXEL CREW — Database Schema Generator
 * 
 * Generates complete, production-grade Prisma schemas (prisma/schema.prisma) and SQL DDL
 * with primary keys, foreign key cascades, unique constraints, and query-derived composite indexes.
 */

import { IndexAnalyzer } from './index-analyzer.js';

export class SchemaGenerator {
  /**
   * Generate complete Prisma schema file
   * @param {Array<object>} entities 
   * @param {object} architecture 
   * @returns {string} Prisma Schema content
   */
  static generatePrismaSchema(entities = [], architecture = {}) {
    const dbType = architecture.database?.type === 'postgresql' ? 'postgresql' : 'sqlite';
    const indexMap = IndexAnalyzer.deriveIndexes(entities, architecture);

    let schema = `// Auto-generated by Pixel Crew Universal Backend Engineering Engine
// Architecture: ${architecture.style || 'modular-monolith'}
// Engine: ${dbType.toUpperCase()}

generator client {
  provider = "prisma-client-js"
}

datasource db {
  provider = "${dbType}"
  url      = env("DATABASE_URL")
}

`;

    entities.forEach(ent => {
      schema += `model ${ent.name} {\n`;
      const fields = ent.fields || [];

      // 1. Render Fields
      fields.forEach(f => {
        let prismaType = 'String';
        if (f.type === 'number') prismaType = 'Int';
        else if (f.type === 'float') prismaType = 'Float';
        else if (f.type === 'boolean') prismaType = 'Boolean';
        else if (f.type === 'datetime') prismaType = 'DateTime';
        else if (f.type === 'json') prismaType = 'Json';

        let line = `  ${f.name.padEnd(16)} ${prismaType}${f.required ? '' : '?'}`;

        if (f.isPrimaryKey) {
          line += ` @id @default(cuid())`;
        } else if (f.default === 'now()') {
          line += ` @default(now())`;
        } else if (f.isUpdatedAt) {
          line += ` @updatedAt`;
        } else if (f.unique || (ent.uniqueFields && ent.uniqueFields.includes(f.name))) {
          line += ` @unique`;
        }

        schema += `${line}\n`;
      });

      // 2. Render Relationships
      const relationships = ent.relationships || [];
      relationships.forEach(rel => {
        const target = rel.targetEntity;
        if (rel.type === 'belongsTo') {
          const fk = rel.foreignKey || `${target.toLowerCase()}Id`;
          schema += `  ${target.toLowerCase().padEnd(16)} ${target} @relation(fields: [${fk}], references: [id], onDelete: Cascade)\n`;
        } else if (rel.type === 'hasMany') {
          schema += `  ${(rel.name || `${target.toLowerCase()}s`).padEnd(16)} ${target}[]\n`;
        }
      });

      // 3. Render Inferred Indexes (Compound & Single)
      const indexes = indexMap[ent.name] || [];
      const nonUniqueIndexes = indexes.filter(idx => !idx.unique && !(idx.fields.length === 1 && idx.fields[0] === 'id'));

      if (nonUniqueIndexes.length > 0) {
        schema += `\n`;
        nonUniqueIndexes.forEach(idx => {
          schema += `  @@index([${idx.fields.join(', ')}])\n`;
        });
      }

      schema += `}\n\n`;
    });

    return schema;
  }
}
